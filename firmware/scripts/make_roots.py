#!/usr/bin/env python3
"""Regenerate src/hal/tls_roots.h: the root certificates the clock trusts for
HTTPS to the bridge. Cloudflare (workers.dev and custom domains) issues from
Let's Encrypt, Google Trust Services and SSL.com; the rest cover other common
hosts. Reads the Mozilla bundle from `certifi` or the system store.

    python3 scripts/make_roots.py
"""
import os
import re
import sys

WANTED = [
    "ISRG Root X1", "ISRG Root X2",
    "GTS Root R1", "GTS Root R3", "GTS Root R4",
    "SSL.com Root Certification Authority RSA", "SSL.com Root Certification Authority ECC",
    "SSL.com TLS RSA Root CA 2022", "SSL.com TLS ECC Root CA 2022",
    "DigiCert Global Root G2",
    "USERTrust RSA Certification Authority", "USERTrust ECC Certification Authority",
    "Amazon Root CA 1",
]

def bundle():
    try:
        import certifi
        return open(certifi.where()).read()
    except ImportError:
        for p in ("/etc/ssl/certs/ca-certificates.crt", "/etc/ssl/cert.pem"):
            if os.path.exists(p):
                return open(p).read()
    sys.exit("No CA bundle found (pip install certifi)")

def main():
    text = bundle()
    certs = {}
    for m in re.finditer(r'# Label: "([^"]+)"\n(?:#[^\n]*\n)*(-----BEGIN CERTIFICATE-----.*?-----END CERTIFICATE-----)', text, re.S):
        certs[m.group(1)] = m.group(2)
    missing = [n for n in WANTED if n not in certs]
    if missing:
        sys.exit(f"Missing from the bundle: {missing}")
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    out = [
        "// Root certificates for HTTPS to the bridge, generated by scripts/make_roots.py",
        "// from the Mozilla CA bundle. Don't edit by hand.",
        "#pragma once",
        "",
        "static const char kTlsRoots[] =",
    ]
    for name in WANTED:
        out.append(f"    // {name}")
        for line in certs[name].strip().splitlines():
            out.append(f'    "{line}\\n"')
    out[-1] += ";"
    open(os.path.join(root, "src", "hal", "tls_roots.h"), "w").write("\n".join(out) + "\n")
    print(f"{len(WANTED)} roots written")

if __name__ == "__main__":
    main()
