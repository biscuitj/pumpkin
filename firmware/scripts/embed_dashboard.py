#!/usr/bin/env python3
"""Build the dashboard (dashboard/) and embed its two pages into
src/hal/web_assets.cpp, gzipped.

The dashboard is rebuilt when a source file is newer than dist/. Without
Node.js an existing dist/ is used as it is. PUMPKIN_SKIP_DASHBOARD_BUILD=1
always uses dist/ as it is.

    python3 scripts/embed_dashboard.py
"""
import gzip
import hashlib
import os
import shutil
import subprocess
import sys

PAGES = [("/index.html", "index.html"), ("/setup.html", "setup.html")]
SOURCES = ["src", "index.html", "setup.html", "vite.config.ts", "package.json", "package-lock.json"]


def newest(paths):
    t = 0.0
    for p in paths:
        if os.path.isfile(p):
            t = max(t, os.path.getmtime(p))
        for base, _, files in os.walk(p):
            for f in files:
                t = max(t, os.path.getmtime(os.path.join(base, f)))
    return t


def build(dash):
    dist = os.path.join(dash, "dist")
    built = [os.path.join(dist, f) for _, f in PAGES]
    have = all(os.path.exists(p) for p in built)
    if os.environ.get("PUMPKIN_SKIP_DASHBOARD_BUILD") == "1":
        if not have:
            sys.exit("[dashboard] PUMPKIN_SKIP_DASHBOARD_BUILD=1 but dashboard/dist is missing")
        return
    stale = not have or newest([os.path.join(dash, s) for s in SOURCES]) > min(os.path.getmtime(p) for p in built)
    if not stale:
        return
    npm = shutil.which("npm")
    if not npm:
        if have:
            print("[dashboard] npm not found: using the existing dashboard/dist")
            return
        sys.exit("[dashboard] The dashboard isn't built and npm isn't installed (Node.js 20+ is needed)")
    if not os.path.isdir(os.path.join(dash, "node_modules")):
        print("[dashboard] npm ci")
        subprocess.run([npm, "ci"], cwd=dash, check=True)
    print("[dashboard] npm run build")
    subprocess.run([npm, "run", "build"], cwd=dash, check=True)


def deterministic_gzip(data):
    out = bytearray(gzip.compress(data, compresslevel=9, mtime=0))
    out[9] = 255  # OS byte: "unknown" everywhere, so builds are byte-identical across systems
    return bytes(out)


def embed(root):
    dash = os.path.join(root, "dashboard")
    build(dash)
    lines = [
        "// Generated by scripts/embed_dashboard.py from dashboard/dist. Don't edit.",
        '#include "web_assets.h"',
        "",
        "#include <string.h>",
        "",
    ]
    entries = []
    for i, (path, name) in enumerate(PAGES):
        raw = open(os.path.join(dash, "dist", name), "rb").read()
        data = deterministic_gzip(raw)
        etag = '\\"' + hashlib.sha256(data).hexdigest()[:16] + '\\"'
        lines.append(f"static const uint8_t kPage{i}[] = {{")
        for j in range(0, len(data), 24):
            lines.append("    " + ", ".join(f"0x{b:02x}" for b in data[j:j + 24]) + ",")
        lines.append("};")
        entries.append(f'    {{"{path}", kPage{i}, sizeof(kPage{i}), "text/html; charset=utf-8", "{etag}", true}},')
        print(f"[dashboard] {path}: {len(raw):,} bytes, {len(data):,} gzipped")
    lines += ["", "const WebAsset kWebAssets[] = {"] + entries + ["};"]
    lines += [
        "const size_t kWebAssetCount = sizeof(kWebAssets) / sizeof(kWebAssets[0]);",
        "",
        "const WebAsset* findWebAsset(const char* path) {",
        "    for (size_t i = 0; i < kWebAssetCount; ++i)",
        "        if (!strcmp(kWebAssets[i].path, path)) return &kWebAssets[i];",
        "    return nullptr;",
        "}",
    ]
    out = os.path.join(root, "src", "hal", "web_assets.cpp")
    text = "\n".join(lines) + "\n"
    if not os.path.exists(out) or open(out).read() != text:
        open(out, "w").write(text)


if __name__ == "__main__":
    embed(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
